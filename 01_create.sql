-- ---------- Remoção das estruturas (ordem inversa das dependências) ----------
DROP VIEW     IF EXISTS vw_resumo_consultas CASCADE;
DROP FUNCTION IF EXISTS fn_validar_conta() CASCADE;
DROP FUNCTION IF EXISTS fn_cancelar_conta_consulta() CASCADE;

DROP TABLE IF EXISTS receita        CASCADE;
DROP TABLE IF EXISTS conta          CASCADE;
DROP TABLE IF EXISTS utiliza        CASCADE;
DROP TABLE IF EXISTS consulta       CASCADE;
DROP TABLE IF EXISTS cardiologista  CASCADE;
DROP TABLE IF EXISTS pediatra       CASCADE;
DROP TABLE IF EXISTS cirurgiao      CASCADE;
DROP TABLE IF EXISTS medico         CASCADE;
DROP TABLE IF EXISTS paciente       CASCADE;
DROP TABLE IF EXISTS plano          CASCADE;

-- ---------- PACIENTE ----------
CREATE TABLE paciente (
    id_usuario            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome                  VARCHAR(60)  NOT NULL,
    sobrenome             VARCHAR(100),
    email                 VARCHAR(100) NOT NULL,
    senha                 VARCHAR(100) NOT NULL,
    data_de_nascimento    DATE         NOT NULL,
    sexo                  CHAR(1),
    cpf                   CHAR(11)     NOT NULL,
    endereco              VARCHAR(200),
    telefone              VARCHAR(20),
    CONSTRAINT pk_paciente         PRIMARY KEY (id_usuario),
    CONSTRAINT uq_paciente_email   UNIQUE (email),
    CONSTRAINT ck_paciente_email   CHECK (email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
    CONSTRAINT ck_paciente_sexo    CHECK (sexo IN ('M', 'F', 'O')),
    CONSTRAINT ck_paciente_nasc    CHECK (data_de_nascimento <= CURRENT_DATE),
    CONSTRAINT uq_paciente_cpf     UNIQUE (cpf),
    CONSTRAINT ck_paciente_cpf     CHECK (cpf ~ '^[0-9]{11}$'));

-- ---------- MEDICO ----------
CREATE TABLE medico (
    id_usuario            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome                  VARCHAR(60)  NOT NULL,
    sobrenome             VARCHAR(100),
    email                 VARCHAR(120) NOT NULL,
    senha                 VARCHAR(255) NOT NULL,
    data_de_nascimento    DATE         NOT NULL,
    sexo                  CHAR(1),
    crm                   VARCHAR(20)   NOT NULL,
    valor_da_consulta     NUMERIC(10,2) NOT NULL,
    telefone_profissional VARCHAR(20),
    CONSTRAINT pk_medico         PRIMARY KEY (id_usuario),
    CONSTRAINT uq_medico_email   UNIQUE (email),
    CONSTRAINT ck_medico_email   CHECK (email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
    CONSTRAINT ck_medico_sexo    CHECK (sexo IN ('M', 'F', 'O')),
    CONSTRAINT ck_medico_nasc    CHECK (data_de_nascimento <= CURRENT_DATE),
    CONSTRAINT uq_medico_crm     UNIQUE (crm),
    CONSTRAINT ck_medico_valor   CHECK (valor_da_consulta > 0));

-- ---------- ESPECIALIZAÇÕES DE MEDICO ----------
CREATE TABLE cardiologista (
    id_usuario             INTEGER,
    realiza_ecocardiograma BOOLEAN NOT NULL,
    CONSTRAINT pk_cardiologista PRIMARY KEY (id_usuario),
    CONSTRAINT fk_cardio_medico FOREIGN KEY (id_usuario)
        REFERENCES medico (id_usuario) ON UPDATE CASCADE ON DELETE CASCADE);

CREATE TABLE pediatra (
    id_usuario             INTEGER,
    faixa_etaria_atendida  VARCHAR(40) NOT NULL,
    atende_recem_nascidos  BOOLEAN     NOT NULL,
    CONSTRAINT pk_pediatra      PRIMARY KEY (id_usuario),
    CONSTRAINT fk_pediatra_med  FOREIGN KEY (id_usuario)
        REFERENCES medico (id_usuario) ON UPDATE CASCADE ON DELETE CASCADE);

CREATE TABLE cirurgiao (
    id_usuario        INTEGER,
    area_cirurgica    VARCHAR(80) NOT NULL,
    tempo_experiencia SMALLINT,   -- em anos
    CONSTRAINT pk_cirurgiao      PRIMARY KEY (id_usuario),
    CONSTRAINT fk_cirurgiao_med  FOREIGN KEY (id_usuario)
        REFERENCES medico (id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ck_cirurgiao_exp  CHECK (tempo_experiencia IS NULL OR tempo_experiencia BETWEEN 0 AND 70));

-- ---------- PLANO ----------
CREATE TABLE plano (
    id_plano            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome_do_plano       VARCHAR(80) NOT NULL,
    telefone_de_contato VARCHAR(20),
    CONSTRAINT pk_plano      PRIMARY KEY (id_plano),
    CONSTRAINT uq_plano_nome UNIQUE (nome_do_plano));

-- ---------- CONSULTA ----------
CREATE TABLE consulta (
    id_consulta         INTEGER GENERATED BY DEFAULT AS IDENTITY,
    data_hora           TIMESTAMP   NOT NULL,
    status              VARCHAR(15) NOT NULL DEFAULT 'Agendada',
    descricao           TEXT,
    id_usuario_medico   INTEGER     NOT NULL,
    id_usuario_paciente INTEGER     NOT NULL,
    CONSTRAINT pk_consulta          PRIMARY KEY (id_consulta),
    CONSTRAINT fk_consulta_medico   FOREIGN KEY (id_usuario_medico)
        REFERENCES medico (id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_consulta_paciente FOREIGN KEY (id_usuario_paciente)
        REFERENCES paciente (id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_consulta_status   CHECK (status IN ('Agendada', 'Realizada')),
    -- regra de negócio: um médico não atende dois pacientes no mesmo horário
    CONSTRAINT uq_consulta_medico_horario UNIQUE (id_usuario_medico, data_hora));

-- ---------- CONTA ----------
CREATE TABLE conta (
    id_conta           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    situacao           VARCHAR(15)   NOT NULL DEFAULT 'Pendente',
    valor_cobrado      NUMERIC(10,2) NOT NULL,
    data_de_vencimento DATE,
    id_usuario         INTEGER       NOT NULL,  -- paciente responsável
    id_consulta        INTEGER       NOT NULL,
    CONSTRAINT pk_conta          PRIMARY KEY (id_conta),
    CONSTRAINT fk_conta_paciente FOREIGN KEY (id_usuario)
        REFERENCES paciente (id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_conta_consulta FOREIGN KEY (id_consulta)
        REFERENCES consulta (id_consulta) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_conta_consulta UNIQUE (id_consulta),   -- 1 conta por consulta
    CONSTRAINT ck_conta_situacao CHECK (situacao IN ('Pendente', 'Paga')),
    CONSTRAINT ck_conta_valor    CHECK (valor_cobrado > 0));

-- ---------- RECEITA ----------
CREATE TABLE receita (
    id_receita    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    prescricao    TEXT NOT NULL,
    orientacao    TEXT,
    data_validade DATE,
    id_consulta   INTEGER NOT NULL,
    CONSTRAINT pk_receita          PRIMARY KEY (id_receita),
    CONSTRAINT fk_receita_consulta FOREIGN KEY (id_consulta)
        REFERENCES consulta (id_consulta) ON UPDATE CASCADE ON DELETE CASCADE);

-- ---------- UTILIZA (médico x paciente x plano) ----------
CREATE TABLE utiliza (
    id_usuario_medico   INTEGER,
    id_usuario_paciente INTEGER,
    id_plano            INTEGER,  -- NULL = atendimento particular
    CONSTRAINT pk_utiliza          PRIMARY KEY (id_usuario_medico, id_usuario_paciente),
    CONSTRAINT fk_utiliza_medico   FOREIGN KEY (id_usuario_medico)
        REFERENCES medico (id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_utiliza_paciente FOREIGN KEY (id_usuario_paciente)
        REFERENCES paciente (id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_utiliza_plano    FOREIGN KEY (id_plano)
        REFERENCES plano (id_plano) ON UPDATE CASCADE ON DELETE SET NULL);